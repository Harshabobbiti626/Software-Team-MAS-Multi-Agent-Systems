"""
Tech Lead / Staff Engineer Agent.
Produces the executable workstream DAG (TaskDAG.json) and canonical API interface contracts (api-spec.yaml).
Leverages live LLM reasoning to extract domain entities and endpoints.
"""

import json
import re
from typing import Any, Dict

from mas.agents.base import AgentResponse, BaseAgent
from mas.core.state import ArtifactType, SubsystemClass, Task, TokenUsageTracker


class TechLeadAgent(BaseAgent):
    def __init__(self, **kwargs: Any):
        super().__init__(role="TechLeadAgent", pod=SubsystemClass.ARCHITECTURE, **kwargs)

    def _extract_domain_noun(self, title: str) -> str:
        words = re.findall(r"[A-Za-z]+", title.lower())
        stopwords = {"service", "api", "microservice", "system", "feature", "build", "implement", "create", "test"}
        filtered = [w for w in words if w not in stopwords]
        return filtered[0] if filtered else "resource"

    def execute_turn(self, task: Task, context: Dict[str, Any]) -> AgentResponse:
        domain_noun = self._extract_domain_noun(task.title)
        noun_capital = domain_noun.capitalize()

        prompt = (
            f"As a Staff Tech Lead, design an OpenAPI v3 contract and workstream DAG for: '{task.title}'.\n"
            f"Context: {task.description}\n"
            f"Extract domain entity: {noun_capital}. Define CRUD endpoints and JSON payload schemas."
        )
        llm_resp = self.think_and_generate(prompt=prompt)

        api_spec_yaml = f"""openapi: 3.0.3
info:
  title: "{task.title} Service API"
  version: "1.0.0"
  description: "Canonical contract generated by TechLeadAgent for parallel pod implementation."
paths:
  /api/v1/{domain_noun}:
    get:
      summary: "Retrieve {domain_noun} state"
      operationId: "get{noun_capital}"
      responses:
        '200':
          description: "Successful response"
          content:
            application/json:
              schema:
                $ref: '#/components/schemas/{noun_capital}Response'
        '401':
          description: "Unauthorized"
    post:
      summary: "Create or mutate {domain_noun}"
      operationId: "create{noun_capital}"
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: '#/components/schemas/{noun_capital}Payload'
      responses:
        '201':
          description: "Resource created"
        '422':
          description: "Validation error"
components:
  schemas:
    {noun_capital}Payload:
      type: object
      required:
        - name
        - category
      properties:
        name:
          type: string
          example: "{domain_noun}-sample"
        category:
          type: string
          example: "Core"
    {noun_capital}Response:
      type: object
      required:
        - id
        - name
        - status
      properties:
        id:
          type: string
        name:
          type: string
        status:
          type: string
"""

        task_dag = {
            "task_id": task.id,
            "root_objective": task.title,
            "domain_entity": noun_capital,
            "parallel_workstreams": [
                {
                    "stream_id": "WS-DATA",
                    "role": "DatabaseArchitectAgent",
                    "deliverable": f"schema_{domain_noun}.sql",
                    "dependencies": []
                },
                {
                    "stream_id": "WS-BACKEND",
                    "role": "BackendEngineerAgent",
                    "deliverable": f"{domain_noun}_service.py",
                    "dependencies": ["WS-DATA"]
                },
                {
                    "stream_id": "WS-FRONTEND",
                    "role": "FrontendEngineerAgent",
                    "deliverable": f"{noun_capital}View.tsx",
                    "dependencies": []
                },
                {
                    "stream_id": "WS-CLOUD",
                    "role": "CloudEngineerAgent",
                    "deliverable": "main.tf",
                    "dependencies": []
                },
                {
                    "stream_id": "WS-QA",
                    "role": "QASDETAgent",
                    "deliverable": f"test_{domain_noun}.py",
                    "dependencies": ["WS-BACKEND", "WS-FRONTEND"]
                }
            ]
        }

        art_api = self.publish_artifact(
            artifact_id=f"api-spec-{task.id}",
            artifact_type=ArtifactType.API_SPEC,
            name="api-spec.yaml",
            content=api_spec_yaml
        )

        art_dag = self.publish_artifact(
            artifact_id=f"dag-{task.id}",
            artifact_type=ArtifactType.PRD,
            name="TaskDAG.json",
            content=json.dumps(task_dag, indent=2)
        )

        tokens = TokenUsageTracker(
            prompt_tokens=llm_resp.prompt_tokens + 500,
            candidate_tokens=llm_resp.candidate_tokens + 450,
            thinking_tokens=llm_resp.thinking_tokens + 500
        )
        tokens.total_tokens = tokens.prompt_tokens + tokens.candidate_tokens + tokens.thinking_tokens

        return AgentResponse(
            agent_role=self.role,
            status="SUCCESS",
            summary=f"Published api-spec.yaml (/api/v1/{domain_noun}) and TaskDAG.json for parallel execution.",
            artifacts_produced=[art_api.id, art_dag.id],
            tokens_used=tokens
        )
