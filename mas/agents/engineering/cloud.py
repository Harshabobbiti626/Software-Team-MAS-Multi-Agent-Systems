"""
Cloud Platform Engineer Agent.
Authors Terraform/OpenTofu Infrastructure-as-Code (IaC), VPC definitions, and IAM least-privilege policies.
"""

from typing import Any, Dict

from mas.agents.base import AgentResponse, BaseAgent
from mas.core.state import ArtifactType, SubsystemClass, Task, TokenUsageTracker


class CloudEngineerAgent(BaseAgent):
    def __init__(self, **kwargs: Any):
        super().__init__(role="CloudEngineerAgent", pod=SubsystemClass.CLOUD_DEVOPS, **kwargs)

    def execute_turn(self, task: Task, context: Dict[str, Any]) -> AgentResponse:
        terraform_hcl = f"""# Terraform IaC for {task.title}
# Generated by CloudEngineerAgent
# Enforces Least-Privilege IAM & Encrypted Storage

terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

resource "aws_kms_key" "service_key" {{
  description             = "KMS key for {task.id}"
  deletion_window_in_days = 30
  enable_key_rotation     = true
}}

resource "aws_security_group" "service_sg" {{
  name        = "sg-{task.id.lower()}"
  description = "Strict least-privilege security group for {task.title}"

  ingress {{
    description = "HTTPS ingress"
    from_port   = 443
    to_port     = 443
    protocol    = "tcp"
    cidr_blocks = ["10.0.0.0/16"]
  }}

  egress {{
    from_port   = 0
    to_port     = 0
    protocol    = "-1"
    cidr_blocks = ["0.0.0.0/0"]
  }}
}}
"""

        artifact = self.publish_artifact(
            artifact_id=f"cloud-iac-{task.id}",
            artifact_type=ArtifactType.CODE_PATCH,
            name="main.tf",
            content=terraform_hcl
        )

        tokens = TokenUsageTracker(prompt_tokens=850, candidate_tokens=420, thinking_tokens=600)
        tokens.total_tokens = 1870

        return AgentResponse(
            agent_role=self.role,
            status="SUCCESS",
            summary="Authored Terraform IaC main.tf with encrypted KMS and least-privilege SG.",
            artifacts_produced=[artifact.id],
            tokens_used=tokens
        )
